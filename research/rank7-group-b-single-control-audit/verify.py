#!/usr/bin/env python3
"""Read-only group-B joint versus single-299 control audit.

Frames are subsets of F2^9 generated by explicit XOR closure. Admission uses
need() and remains active under python -O. This module does not import
independent.py or any predecessor verifier.
"""

from __future__ import annotations

import copy
import gzip
import hashlib
import io
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MARKER = (
    "PASS_RANK7_GROUP_B_SINGLE_CONTROL "
    "joint_margin=42541 single299_margin=-58943 "
    "widths=7/6/6/6/6 placements=3330 no_new_kappa"
)
INPUTS = (
    "research/rank7-joint-endframes/data/STAGE1-FRAME-EDITS.json",
    "research/rank7-joint-endframes/construction/STAGE-PRICES.json",
    "research/rank7-joint-endframes/data/PARENT-base.json.gz",
    "research/rank7-joint-endframes/data/PARENT-extra.json.gz",
    "research/rank7-joint-endframes/data/WORD-base.json.gz",
    "research/rank7-joint-endframes/data/WORD-extra.json.gz",
    "research/rank7-joint-endframes/allocation/FILL.json.gz",
)
HELPERS = (299, 448, 449, 484, 485)
SHARED_W = [256, 128, 64, 34, 17, 11, 4]
LIMIT = 64 * 1024 * 1024


def need(ok, message):
    if not ok:
        raise ValueError(message)


def pairs_unique(pairs):
    value = {}
    for key, item in pairs:
        need(key not in value, "duplicate JSON key")
        value[key] = item
    return value


def read_json(path):
    raw = Path(path).read_bytes()
    need(len(raw) <= LIMIT, "input exceeds capacity")
    return json.loads(raw, object_pairs_hook=pairs_unique)


def decode(raw, compressed=False):
    if compressed:
        with gzip.GzipFile(fileobj=io.BytesIO(raw)) as stream:
            raw = stream.read(LIMIT + 1)
    need(len(raw) <= LIMIT, "decoded input capacity")
    return json.loads(raw, object_pairs_hook=pairs_unique)


def pin_sources():
    manifest = read_json(HERE / "SOURCES.json")
    rows = [row for row in manifest["files"] if row["usage"] == "input"]
    need(tuple(row["path"] for row in rows) == INPUTS, "input inventory")
    pinned = {}
    for row in rows:
        path = ROOT / row["path"]
        raw = path.read_bytes()
        need(len(raw) <= LIMIT, "source size")
        digest = hashlib.sha256(raw).hexdigest()
        need(digest == row["sha256"], "source hash: " + row["path"])
        pinned[row["path"]] = raw
    return pinned


def span(vectors):
    points = {0}
    for vector in vectors:
        need(type(vector) is int and 0 < vector < 512, "nine-bit generator")
        points |= {point ^ vector for point in points}
    need(len(points) == 1 << len(vectors), "independent frame generators")
    return frozenset(points)


def dimension(space):
    return len(space).bit_length() - 1


ZERO = span(())
FULL = span(tuple(1 << bit for bit in range(9)))


def group_b_edits(record):
    need(record["groups"]["B"][0] == SHARED_W, "declared shared W")
    need(record["groups"]["B"][1] == list(HELPERS), "declared helpers")
    spaces = {name: span(tuple(pair[0])) for name, pair in record["groups"].items()}
    need(dimension(spaces["B"]) == 7, "rank-seven group B")
    edits = []
    for edit in record["frame_edits"]:
        old = span(tuple(edit["old_frame"]))
        new = span(tuple(edit["new_frame"]))
        need(new < old and len(old) == 2 * len(new), "one-dimensional gate lowering")
        owners = [name for name, space in spaces.items() if new <= space]
        need(len(owners) == 1, "unambiguous edited-frame group")
        if owners[0] == "B":
            edits.append(edit)
    need(len(edits) == 21, "group B gate-edit count")
    return edits


def apply_group_b(parent, record, endpoints):
    child = copy.deepcopy(parent)
    edits = group_b_edits(record)
    chosen = set(endpoints)
    need(chosen <= set(HELPERS), "subset of group B")
    for helper in sorted(chosen):
        change = record["helper_final_changes"][str(helper)]
        need(parent["helper_final"][str(helper)] == change["old"], "endpoint preimage")
        need(change["new"] == SHARED_W, "endpoint image is shared W")
        child["helper_final"][str(helper)] = list(SHARED_W)
    for edit in edits:
        section, index = edit["section"], edit["index"]
        gate = parent[section][index]
        need(
            gate[:-1] == edit["gate"] and gate[-1] == edit["old_frame"],
            "gate edit preimage",
        )
        child[section][index][-1] = list(edit["new_frame"])
    need(child["cleanup"] == parent["cleanup"], "cleanup unchanged")
    for section in ("A", "B", "restore"):
        for old, new in zip(parent[section], child[section], strict=True):
            need(old[:-1] == new[:-1], "scalar/operator word unchanged")
    return child


def boundaries(word):
    ports = word["ports"]
    need(len(ports) == 112, "112 ports")
    starts = [span((port,)) for port in ports] + [ZERO] * 592
    ends = (
        [FULL] * 112
        + [
            frozenset(x for x in range(512) if (x & port).bit_count() % 2 == 0)
            for port in ports
        ]
        + [FULL] * 480
    )
    for field, frames in (("start_extra", starts), ("helper_final", ends)):
        for role, vectors in word[field].items():
            frames[int(role)] = span(tuple(vectors))
    live = set(range(704)) - set(word["removed"])
    need(len(live) == 632, "live geometry")
    widths = Counter()
    for role in sorted(live - set(range(224))):
        need(starts[role] <= ends[role], "entrance inside terminal")
        widths[dimension(ends[role]) - dimension(starts[role])] += 1
    return starts, ends, live, dict(sorted(widths.items()))


def climb(current, paid, role, destination):
    source = current[role]
    need(source <= destination, "nonmonotone climb")
    rank = dimension(destination) - dimension(source)
    if rank:
        paid[rank] += 1
    current[role] = destination


def roles(gate):
    need(gate[0] in ("add", "scale"), "scalar gate kind")
    return gate[1:3] if gate[0] == "add" else gate[1:2]


def warp(current, role, columns, old, new, inverse=False):
    old_space, new_space = span(tuple(old)), span(tuple(new))
    source, target = (new_space, old_space) if inverse else (old_space, new_space)
    need(current[role] == source, "warp entrance")
    current[role] = target


def scalar_step(word, current, paid, gate):
    if gate[0] == "warp":
        role, operator, old, new = gate[1:]
        columns = word["warps"][abs(operator) - 1][2]
        if operator < 0:
            warp(current, role, columns, new, old, inverse=True)
        else:
            warp(current, role, columns, old, new)
        return
    destination = span(tuple(gate[-1]))
    for role in roles(gate):
        climb(current, paid, role, destination)


def centre_copies(word, current, paid):
    need(len(word["centers"]) == len(word["center_frames"]) == 8, "eight centres")
    for role, frame in zip(word["centers"], word["center_frames"], strict=True):
        source = span(tuple(frame))
        need(current[role] == source, "centre entrance")
        readers = {
            span(tuple(word["target_levels"].get(str(gate[1] - 112), [])))
            for gate in word["cut"]
            if gate[2] == role
        }
        for target in sorted(readers, key=lambda space: (-len(space), tuple(sorted(space)))):
            need(target <= source, "nested centre copy")
            rank = dimension(source) - dimension(target)
            if rank:
                paid[rank] += 1
            source = target


def ledger(word):
    current, ends, live, widths = boundaries(word)
    paid = Counter()
    for gate in word["A"]:
        scalar_step(word, current, paid, gate)
    centre_copies(word, current, paid)
    by_position = {}
    for position, role, columns, old, new in word["warps"]:
        by_position.setdefault(position, []).append((role, columns, old, new))
    for index in range(len(word["B"]) + 1):
        for role, columns, old, new in by_position.get(index, []):
            warp(current, role, columns, old, new)
        if index < len(word["B"]):
            scalar_step(word, current, paid, word["B"][index])
    for gate in word["restore"]:
        scalar_step(word, current, paid, gate)
    for role in sorted(live):
        climb(current, paid, role, ends[role])
    return dict(sorted(paid.items())), widths


def helper_width(word, helper):
    end = word["helper_final"].get(str(helper))
    end_dim = 9 if end is None else dimension(span(tuple(end)))
    start = word.get("start_extra", {}).get(str(helper), [])
    start_dim = 0 if not start else dimension(span(tuple(start)))
    width = end_dim - start_dim
    need(width > 0, "positive width")
    return width


def profile_delta(after, before):
    keys = sorted(set(after) | set(before))
    return {
        str(rank): after.get(rank, 0) - before.get(rank, 0)
        for rank in keys
        if after.get(rank, 0) != before.get(rank, 0)
    }


def price(profile, coefficients):
    return sum(coefficients[rank] * count for rank, count in profile.items())


def fill_placements(fill, parent):
    live = [role for role in range(224, 704) if role not in parent["removed"]]
    need(len(live) == 408, "408 helpers")
    indexes = {helper: live.index(helper) for helper in HELPERS}
    counts = Counter()
    need(fill["columns"] == ["time", "helper", "owner_replica", "child", "port", "offset"], "fill columns")
    need(len(fill["rows"]) == 666 * 408, "fill role count")
    for row in fill["rows"]:
        need(len(row) == 6 and all(type(value) is int for value in row), "integer fill row")
        helper_index = row[1]
        for helper, index in indexes.items():
            if helper_index == index:
                counts[helper] += 1
    need(dict(counts) == {helper: 666 for helper in HELPERS}, "one placement per call")
    return 666, 3330


def provider_receipt(tag, parent, shipped, record, coefficients, break_even, fill):
    joint = apply_group_b(parent, record, HELPERS)
    single = apply_group_b(parent, record, (299,))
    for helper in HELPERS:
        need(joint["helper_final"][str(helper)] == SHARED_W, "joint endpoint")
        need(shipped["helper_final"][str(helper)] == SHARED_W, "shipped endpoint")
    parent_profile, _ = ledger(parent)
    joint_profile, _ = ledger(joint)
    single_profile, _ = ledger(single)
    need(
        parent_profile == {int(rank): count for rank, count in parent["report"]["local_profile"].items()},
        "parent report profile",
    )
    joint_delta = price(joint_profile, coefficients) - price(parent_profile, coefficients)
    single_delta = price(single_profile, coefficients) - price(parent_profile, coefficients)
    joint_widths = {str(helper): helper_width(joint, helper) for helper in HELPERS}
    single_widths = {str(helper): helper_width(single, helper) for helper in HELPERS}
    parent_widths = {str(helper): helper_width(parent, helper) for helper in HELPERS}
    joint_freed = sum(parent_widths[str(h)] - joint_widths[str(h)] for h in HELPERS)
    single_freed = sum(parent_widths[str(h)] - single_widths[str(h)] for h in HELPERS)
    need(joint_freed == 5 and single_freed == 1, "freed width units")
    joint_margin = -joint_delta - break_even * joint_freed
    single_margin = -single_delta - break_even * single_freed
    per_helper, group_total = fill_placements(fill, parent)
    return {
        "provider": tag,
        "parent_profile": {str(rank): count for rank, count in parent_profile.items()},
        "joint_profile_delta": profile_delta(joint_profile, parent_profile),
        "single299_profile_delta": profile_delta(single_profile, parent_profile),
        "joint_delta_units": joint_delta,
        "single299_delta_units": single_delta,
        "joint_freed_width_units": joint_freed,
        "single299_freed_width_units": single_freed,
        "joint_margin": joint_margin,
        "single299_margin": single_margin,
        "parent_widths": parent_widths,
        "joint_widths": joint_widths,
        "single299_widths": single_widths,
        "start_extra": {
            str(helper): parent.get("start_extra", {}).get(str(helper), [])
            for helper in HELPERS
        },
        "fill_placements_per_helper": per_helper,
        "fill_group_placements": group_total,
    }


def build_receipt(pinned):
    record = decode(pinned["research/rank7-joint-endframes/data/STAGE1-FRAME-EDITS.json"])
    prices = decode(pinned["research/rank7-joint-endframes/construction/STAGE-PRICES.json"])
    fill = decode(pinned["research/rank7-joint-endframes/allocation/FILL.json.gz"], True)
    coefficients = {int(rank): value for rank, value in prices["weights"]["c"].items()}
    break_even = prices["weights"]["break_even"]
    need(break_even == 2091300, "pinned break-even guide")
    group = next(row for row in prices["stage1"]["groups"] if row["group"] == "B")
    need(group["W"] == SHARED_W and group["helpers"] == list(HELPERS), "STAGE-PRICES group B")
    providers = {}
    for tag in ("base", "extra"):
        parent = decode(
            pinned[f"research/rank7-joint-endframes/data/PARENT-{tag}.json.gz"], True
        )
        shipped = decode(
            pinned[f"research/rank7-joint-endframes/data/WORD-{tag}.json.gz"], True
        )
        providers[tag] = provider_receipt(
            tag, parent, shipped, record, coefficients, break_even, fill
        )
    need(providers["base"]["joint_margin"] == providers["extra"]["joint_margin"] == 42541, "joint margin")
    need(
        providers["base"]["single299_margin"]
        == providers["extra"]["single299_margin"]
        == -58943,
        "single margin",
    )
    need(providers["base"]["joint_delta_units"] == group["joint_delta"], "joint delta pin")
    need(providers["base"]["joint_margin"] == group["joint_margin"], "joint margin pin")
    need(
        providers["base"]["single299_margin"] == group["singles_margin"]["299"],
        "single margin pin",
    )
    need(
        providers["base"]["joint_widths"]
        == {"299": 7, "448": 6, "449": 6, "484": 6, "485": 6},
        "joint widths",
    )
    return {
        "schema_version": 1,
        "claim_id": "rank7-group-b-single-control-audit",
        "pinned_main": "6f100d4bb5083f8c35d96fd95a539811c62f245c",
        "group": "B",
        "shared_W": SHARED_W,
        "helpers": list(HELPERS),
        "gate_edits": 21,
        "break_even_guide": break_even,
        "joint_profile_delta": providers["base"]["joint_profile_delta"],
        "single299_profile_delta": providers["base"]["single299_profile_delta"],
        "joint_delta_units": providers["base"]["joint_delta_units"],
        "single299_delta_units": providers["base"]["single299_delta_units"],
        "joint_margin": 42541,
        "single299_margin": -58943,
        "joint_widths": providers["base"]["joint_widths"],
        "single299_widths": providers["base"]["single299_widths"],
        "fill_placements_per_helper": 666,
        "fill_group_placements": 3330,
        "providers": providers,
        "obstruction_or_result": "group_B_joint_wins_single299_loses_on_guide",
        "no_new_kappa": True,
        "selected_kappa": "0.001672660197076918",
    }


def evaluate():
    pinned = pin_sources()
    receipt = build_receipt(pinned)
    need(receipt["no_new_kappa"] is True, "kappa claim crept in")
    need(receipt["joint_margin"] > 0, "joint should win on guide")
    need(receipt["single299_margin"] < 0, "single-299 should lose on guide")
    return receipt


def admit(observed, expected):
    need(observed == expected, "certificate mismatch")


def main():
    observed = evaluate()
    expected = read_json(HERE / "CERTIFICATE.json")
    admit(observed, expected)
    print(MARKER)


if __name__ == "__main__":
    main()
